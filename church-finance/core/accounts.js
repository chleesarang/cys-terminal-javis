export function accountLabel(a) {
  return a ? `${a.gwan} › ${a.name}` : '미분류';
}

/** 다음 사용 가능한 코드 (수입 1xx, 지출 2xx~) */
export function nextAccountId(accounts, kind) {
  const base = kind === 'in' ? 100 : 200;
  const used = new Set(accounts.map((a) => +a.id));
  for (let i = base + 1; i < base + 900; i++) if (!used.has(i)) return String(i);
  throw new Error('계정 코드가 가득 찼습니다');
}
